use crate::{source::Span, symbol::Symbol};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Keyword {
    Module,
    Import,
    Pub,
    Package,
    Type,
    Struct,
    Union,
    Enum,
    Trait,
    Impl,
    Extern,
    Contract,
    Requires,
    Ensures,
    Assume,
    Because,
    Const,
    StaticAssert,
    Auto,
    Mut,
    Move,
    Scope,
    Spawn,
    Defer,
    Return,
    If,
    Else,
    While,
    For,
    In,
    Break,
    Continue,
    Match,
    True,
    False,
    Null,
    Dyn,
    Fn,
}

impl Keyword {
    fn spelling(self) -> &'static str {
        match self {
            Self::Module => "module",
            Self::Import => "import",
            Self::Pub => "pub",
            Self::Package => "package",
            Self::Type => "type",
            Self::Struct => "struct",
            Self::Union => "union",
            Self::Enum => "enum",
            Self::Trait => "trait",
            Self::Impl => "impl",
            Self::Extern => "extern",
            Self::Contract => "contract",
            Self::Requires => "requires",
            Self::Ensures => "ensures",
            Self::Assume => "assume",
            Self::Because => "because",
            Self::Const => "const",
            Self::StaticAssert => "static_assert",
            Self::Auto => "auto",
            Self::Mut => "mut",
            Self::Move => "move",
            Self::Scope => "scope",
            Self::Spawn => "spawn",
            Self::Defer => "defer",
            Self::Return => "return",
            Self::If => "if",
            Self::Else => "else",
            Self::While => "while",
            Self::For => "for",
            Self::In => "in",
            Self::Break => "break",
            Self::Continue => "continue",
            Self::Match => "match",
            Self::True => "true",
            Self::False => "false",
            Self::Null => "null",
            Self::Dyn => "dyn",
            Self::Fn => "fn",
        }
    }
    pub fn from_text(text: &str) -> Option<Self> {
        Some(match text {
            "module" => Self::Module,
            "import" => Self::Import,
            "pub" => Self::Pub,
            "package" => Self::Package,
            "type" => Self::Type,
            "struct" => Self::Struct,
            "union" => Self::Union,
            "enum" => Self::Enum,
            "trait" => Self::Trait,
            "impl" => Self::Impl,
            "extern" => Self::Extern,
            "contract" => Self::Contract,
            "requires" => Self::Requires,
            "ensures" => Self::Ensures,
            "assume" => Self::Assume,
            "because" => Self::Because,
            "const" => Self::Const,
            "static_assert" => Self::StaticAssert,
            "auto" => Self::Auto,
            "mut" => Self::Mut,
            "move" => Self::Move,
            "scope" => Self::Scope,
            "spawn" => Self::Spawn,
            "defer" => Self::Defer,
            "return" => Self::Return,
            "if" => Self::If,
            "else" => Self::Else,
            "while" => Self::While,
            "for" => Self::For,
            "in" => Self::In,
            "break" => Self::Break,
            "continue" => Self::Continue,
            "match" => Self::Match,
            "true" => Self::True,
            "false" => Self::False,
            "null" => Self::Null,
            "dyn" => Self::Dyn,
            "fn" => Self::Fn,
            _ => return None,
        })
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TokenKind {
    Ident(Symbol),
    Lifetime(Symbol),
    Keyword(Keyword),
    Underscore,
    Integer,
    Float,
    String,
    Char,
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    Semicolon,
    Colon,
    ColonColon,
    Comma,
    Dot,
    DotDot,
    Ellipsis,
    At,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Amp,
    Pipe,
    Caret,
    Bang,
    Tilde,
    Equal,
    Less,
    Greater,
    LessEqual,
    GreaterEqual,
    EqualEqual,
    BangEqual,
    AmpAmp,
    PipePipe,
    ShiftLeft,
    ShiftRight,
    Arrow,
    FatArrow,
    Question,
    PlusEqual,
    MinusEqual,
    StarEqual,
    SlashEqual,
    PercentEqual,
    AmpEqual,
    PipeEqual,
    CaretEqual,
    ShiftLeftEqual,
    ShiftRightEqual,
    Eof,
}

impl std::fmt::Display for TokenKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let text = match self {
            Self::Ident(_) => "an identifier",
            Self::Lifetime(_) => "a lifetime",
            Self::Integer => "an integer literal",
            Self::Float => "a floating-point literal",
            Self::String => "a string literal",
            Self::Char => "a character literal",
            Self::Eof => "end of file",
            Self::Keyword(keyword) => return write!(f, "`{}`", keyword.spelling()),
            Self::Underscore => "`_`",
            Self::LeftParen => "`(`",
            Self::RightParen => "`)`",
            Self::LeftBrace => "`{`",
            Self::RightBrace => "`}`",
            Self::LeftBracket => "`[`",
            Self::RightBracket => "`]`",
            Self::Semicolon => "`;`",
            Self::Colon => "`:`",
            Self::ColonColon => "`::`",
            Self::Comma => "`,`",
            Self::Dot => "`.`",
            Self::DotDot => "`..`",
            Self::Ellipsis => "`...`",
            Self::At => "`@`",
            Self::Plus => "`+`",
            Self::Minus => "`-`",
            Self::Star => "`*`",
            Self::Slash => "`/`",
            Self::Percent => "`%`",
            Self::Amp => "`&`",
            Self::Pipe => "`|`",
            Self::Caret => "`^`",
            Self::Bang => "`!`",
            Self::Tilde => "`~`",
            Self::Equal => "`=`",
            Self::Less => "`<`",
            Self::Greater => "`>`",
            Self::LessEqual => "`<=`",
            Self::GreaterEqual => "`>=`",
            Self::EqualEqual => "`==`",
            Self::BangEqual => "`!=`",
            Self::AmpAmp => "`&&`",
            Self::PipePipe => "`||`",
            Self::ShiftLeft => "`<<`",
            Self::ShiftRight => "`>>`",
            Self::Arrow => "`->`",
            Self::FatArrow => "`=>`",
            Self::Question => "`?`",
            Self::PlusEqual => "`+=`",
            Self::MinusEqual => "`-=`",
            Self::StarEqual => "`*=`",
            Self::SlashEqual => "`/=`",
            Self::PercentEqual => "`%=`",
            Self::AmpEqual => "`&=`",
            Self::PipeEqual => "`|=`",
            Self::CaretEqual => "`^=`",
            Self::ShiftLeftEqual => "`<<=`",
            Self::ShiftRightEqual => "`>>=`",
        };
        f.write_str(text)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}
